/**
 * Fill `team_review_requests` for the pull requests open today. The webhook
 * keeps it current after that.
 *
 *   npm run backfill:team-requests -- --out worker/team-requests.sql
 *   cd worker && npx wrangler d1 execute nh-dashboard --remote --file team-requests.sql
 *
 * Reading a team needs org read, which `gh auth token` has for an org member and
 * the build's PAT may not. Run it locally.
 */

import { writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";

import { graphql, stats } from "../src/github/client.js";
import { ORG, isIngestExcluded } from "../src/config.js";

const args = new Map();
for (let i = 2; i < process.argv.length; i++) {
  const [key, inline] = process.argv[i].replace(/^--/, "").split("=");
  if (!process.argv[i].startsWith("--")) continue;
  const next = process.argv[i + 1];
  if (inline !== undefined) args.set(key, inline);
  else if (next && !next.startsWith("--")) args.set(key, process.argv[++i]);
  else args.set(key, true);
}

const OUT = args.get("out") ?? "worker/team-requests.sql";

const REQUESTS = `reviewRequests(first: 20) { nodes { requestedReviewer { ... on Team { databaseId } } } }`;
const OPEN = `number updatedAt ${REQUESTS}`;

const REPOS = `query($org: String!, $cursor: String) {
  organization(login: $org) { repositories(first: 25, after: $cursor) {
    pageInfo { hasNextPage endCursor }
    nodes { name pullRequests(states: OPEN, first: 50) { pageInfo { hasNextPage endCursor } nodes { ${OPEN} } } }
  } }
}`;

const MORE = `query($org: String!, $name: String!, $cursor: String) {
  repository(owner: $org, name: $name) { pullRequests(states: OPEN, first: 50, after: $cursor) {
    pageInfo { hasNextPage endCursor } nodes { ${OPEN} } } }
}`;

const q = (v) => `'${String(v).replace(/'/g, "''")}'`;

export const teamsOf = (pr) =>
  (pr.reviewRequests?.nodes ?? []).map((n) => n.requestedReviewer?.databaseId).filter(Number.isSafeInteger);

// Never over a row the webhook has since moved on.
export const updateSql = (repo, pr) =>
  `UPDATE pull_requests SET team_review_requests = ${q(JSON.stringify(teamsOf(pr)))} ` +
  `WHERE repo = ${q(repo)} AND number = ${Number(pr.number)} AND updated_at <= ${q(pr.updatedAt)};\n`;

async function main() {
  const lines = [`-- Generated by worker/backfill-team-requests.js on ${new Date().toISOString()}\n`];
  let prs = 0;
  let requested = 0;
  const take = (name, nodes) => {
    for (const pr of nodes ?? []) {
      lines.push(updateSql(name, pr));
      prs++;
      if (teamsOf(pr).length) requested++;
    }
  };
  for (let cursor = null; ;) {
    const page = (await graphql(REPOS, { org: ORG, cursor })).organization.repositories;
    for (const repo of page.nodes ?? []) {
      if (!repo?.name || isIngestExcluded(repo.name)) continue;
      take(repo.name, repo.pullRequests.nodes);
      for (let more = repo.pullRequests.pageInfo; more.hasNextPage;) {
        const next = (await graphql(MORE, { org: ORG, name: repo.name, cursor: more.endCursor })).repository.pullRequests;
        take(repo.name, next.nodes);
        more = next.pageInfo;
      }
    }
    if (!page.pageInfo.hasNextPage) break;
    cursor = page.pageInfo.endCursor;
  }
  await writeFile(OUT, lines.join(""));
  console.log(`\n  ${prs} open pull requests, ${requested} with a team asked to review\n  ${stats.requests} API requests\n\n  wrote ${OUT}\n\n` +
    `  cd worker && npx wrangler d1 execute nh-dashboard --remote --file ${OUT.replace(/^worker\//, "")}\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((err) => {
    console.error(`\n  failed: ${err.message}\n`);
    process.exit(1);
  });
}
