/**
 * Fill in D1's `closed_at` from the ingest store.
 *
 *   node --env-file-if-exists=.env worker/backfill-closed-at.js
 *   cd worker && npx wrangler d1 execute nh-dashboard --remote --file closed-at.sql
 *
 * Why this rather than a wider `backfill-prs.js --since`: that walks GitHub and
 * rewrites every pull request and every review row to correct one column on the
 * 7% of them that were closed without merging. This reads the column out of the
 * store the ingest has already populated and touches nothing else — no API
 * requests at all, and roughly 2,000 writes against the 29,000 rows and 41,000
 * review rows a full reconcile would rewrite.
 *
 * It exists because the two halves learned the field at different times. D1 has
 * carried a `closed_at` column since the first schema and the webhook handler
 * has always written it, but the ingest never queried it, so `seed.js` loaded
 * every row with a null one and only PRs closed since the webhook went live
 * have a real value. `medianAbandonHours` over that sample is a median of a
 * handful of rows — a number that looks like every other number on the card.
 *
 * Run it after an ingest that has completed the close-timestamp backfill.
 * Records that still lack `closedAt` are skipped rather than written as null,
 * so a partial store narrows the fix rather than corrupting what is there.
 *
 * Idempotent, and safe to re-run: every statement is guarded on the D1 row
 * still being an unmerged closure with no timestamp, so a value a webhook has
 * since delivered is never overwritten by an older one from the store, and a
 * PR reopened since the store was written is left alone.
 */

import { createWriteStream } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { readStore } from "../src/ingest/pullRequests.js";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, "closed-at.sql");

const q = (v) => (v == null ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);

const isAbandoned = (p) => p.state === "CLOSED" && !p.mergedAt;

async function main() {
  console.log("\nReading close timestamps out of the ingest store\n");

  const prs = await readStore();
  if (!prs.length) throw new Error("the store is empty — run `npm run ingest` first");

  const abandoned = prs.filter(isAbandoned);
  const rows = abandoned.filter((p) => p.closedAt);
  const missing = abandoned.length - rows.length;

  console.log(`  ${prs.length} pull requests in the store`);
  console.log(`  ${abandoned.length} closed without merging`);
  console.log(`  ${rows.length} of them carry a close timestamp`);

  if (missing) {
    console.log(
      `\n  ${missing} still have none. That is the close-timestamp backfill not\n` +
        `  having finished — run \`npm run ingest\` again and re-run this.\n`
    );
  }

  // An empty file is worse than no file: applied, it is a silent no-op that
  // reads as a completed repair. Same reason backfill-repo-labels.js refuses.
  if (!rows.length) {
    throw new Error(
      "no close timestamps in the store; refusing to write an empty file"
    );
  }

  const out = createWriteStream(OUT);
  out.write(`-- Generated by worker/backfill-closed-at.js on ${new Date().toISOString()}\n`);
  out.write(`-- ${rows.length} close timestamps for pull requests closed without merging\n\n`);

  // One statement per row rather than a batched UPDATE ... FROM (VALUES ...).
  // The batched form is fewer statements and depends on a SQLite version D1
  // does not promise; at two thousand rows the saving buys nothing worth a
  // dialect assumption, and this file is applied once.
  for (const p of rows) {
    out.write(
      `UPDATE pull_requests SET closed_at = ${q(p.closedAt)}\n` +
        ` WHERE repo = ${q(p.repo)} AND number = ${p.number}\n` +
        `   AND merged_at IS NULL AND state = 'CLOSED' AND closed_at IS NULL;\n`
    );
  }

  await new Promise((resolve) => out.end(resolve));

  console.log(`\n  wrote ${rows.length} statements to ${path.relative(process.cwd(), OUT)}\n`);
  console.log("  Apply with:");
  console.log("    cd worker && npx wrangler d1 execute nh-dashboard --remote --file closed-at.sql\n");
  console.log("  Then rebuild the cached panels:");
  console.log('    curl -fsS -X POST "https://nh-dashboard.gtnh.workers.dev/api/recompute?force=1"\n');
}

main().catch((err) => {
  console.error(`\n  ${err.message}\n`);
  process.exit(1);
});
